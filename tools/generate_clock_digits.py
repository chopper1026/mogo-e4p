"""中文：以确认稿的224px字号生成十个4bpp游程数字。/ Generate the approved 224px digits as 4bpp runs."""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageChops, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'main/assets/clock-font/ChakraPetch-Bold.ttf'
OUTPUT = ROOT / 'main/assets/clock_digits.h'

def generate():
    font = ImageFont.truetype(str(FONT), 224)
    advance = round(max(font.getlength(digit) for digit in '0123456789'))
    data, entries = [], []
    for digit in '0123456789':
        canvas = Image.new('L', (advance + 32, 312), 255)
        ImageDraw.Draw(canvas).text((16, 224), digit, font=font, anchor='ls', fill=0)
        box = ImageChops.invert(canvas).getbbox()
        image = canvas.crop(box)
        # 颜色采用固件高四位，不依赖PNG或运行时字库。/ Store the firmware's high nibble directly.
        pixels = [v >> 4 for v in image.tobytes()]
        offset = len(data)
        at = 0
        while at < len(pixels):
            count = 1
            while at + count < len(pixels) and count < 16 and pixels[at + count] == pixels[at]:
                count += 1
            data.append(((count - 1) << 4) | pixels[at])
            at += count
        entries.append((offset, len(data) - offset, image.width, image.height, box[1] - 224))
    lines = ['/* Generated by tools/generate_clock_digits.py; do not edit.',
             ' * Chakra Petch Bold, SIL OFL 1.1: clock-font/OFL.txt.',
             ' * Source SHA-256: ' + hashlib.sha256(FONT.read_bytes()).hexdigest() + ' */',
             '#pragma once', '#include <stdint.h>',
             '#define CLOCK_DIGIT_CELL 145', '#define CLOCK_DIGIT_TRACKING 6',
             'typedef struct { uint32_t offset, length; uint16_t width, height; int16_t top; } clock_digit_t;',
             'static const clock_digit_t clock_digits[10] = {']
    assert advance == 145
    lines += ['    {' + ','.join(map(str, entry)) + '},' for entry in entries]
    lines += ['};', 'static const uint8_t clock_digit_runs[] = {']
    lines += ['    ' + ','.join(f'0x{v:02x}' for v in data[i:i+24]) + ',' for i in range(0, len(data), 24)]
    return '\n'.join(lines + ['};', ''])

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Clock digits differ; run tools/generate_clock_digits.py')
    else:
        OUTPUT.write_text(content)
    print(f'Clock digits {"verified" if args.check else "generated"}: {OUTPUT}')
