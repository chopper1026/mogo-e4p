"""中文：从OFL数字子集生成一位衬线数字，锁屏不加载第二份字库。
English: Generate monochrome serif digits from an OFL subset without loading another runtime face.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parents[1]

def main():
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    source = ROOT/'tools/vendor/libre-bodoni/digits.ttf'
    font = ImageFont.truetype(str(source), 384)
    data, widths, offsets = bytearray(), [], []
    for digit in '0123456789':
        x0,y0,x1,y1 = font.getbbox(digit)
        image = Image.new('L',(x1-x0,y1-y0)); ImageDraw.Draw(image).text((-x0,-y0),digit,font=font,fill=255)
        width = round(image.width*256/image.height)
        image = image.resize((width,256),Image.Resampling.LANCZOS)
        widths.append(width); offsets.append(len(data)); stride=(width+7)//8
        packed=bytearray(stride*256)
        for y in range(256):
            for x in range(width):
                if image.getpixel((x,y))>=128: packed[y*stride+x//8] |= 1 << (7-x%8)
        data.extend(packed)
    header = '// Generated by tools/generate_calendar_digits.py; Libre Bodoni (SIL OFL 1.1).\n'
    header += '// 中文：只含数字，许可见 tools/vendor/libre-bodoni/OFL.txt。/ English: Digits only; retain the OFL notice.\n#pragma once\n'
    header += '// Input SHA-256: '+hashlib.sha256(source.read_bytes()).hexdigest()+'\n'
    header += 'static const uint16_t calendar_digit_widths[]={'+','.join(map(str,widths))+'};\n'
    header += 'static const uint32_t calendar_digit_offsets[]={'+','.join(map(str,offsets))+'};\n'
    header += 'static const uint8_t calendar_digit_bits[]={\n'
    header += ',\n'.join(','.join(str(v) for v in data[i:i+32]) for i in range(0,len(data),32))+'\n};\n'
    target=ROOT/'main/assets/calendar_digits.h'
    if args.check: assert target.read_text()==header, 'Stale calendar digits'
    else: target.write_text(header)
    print(f'Calendar serif digits: {len(data)} bytes')

if __name__=='__main__': main()
